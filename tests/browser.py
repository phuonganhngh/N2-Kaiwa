"""Browser flow checks. Start npm start first. Requires Python Playwright.
Uses system Chromium when available; set N2_BROWSER=webkit for WebKit.
"""
import json
import os
import re
import shutil
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
BASE = os.environ.get('N2_TEST_URL', 'http://127.0.0.1:8000')
bank = json.loads((ROOT / 'data/exercises.json').read_text())
checks = 0

def check(condition, label):
    global checks
    assert condition, label
    checks += 1
    print('PASS', label)

def prompt(page, count):
    check(not page.locator('#handoff-dialog').is_visible(), 'successful copy has no extra dialog')
    value = page.evaluate('window.__copied')
    check(len(re.findall(r'^Exercise \d+$', value, re.M)) == count, f'exactly {count} copied exercises')
    check(all(e['japaneseModelAnswer'] not in value for e in bank), 'no model answers in copied prompt')
    return value

with sync_playwright() as p:
    name = os.environ.get('N2_BROWSER','chromium')
    options = {'headless': True}
    if name == 'chromium' and shutil.which('chromium'):
        options['executable_path'] = shutil.which('chromium')
    browser = getattr(p,name).launch(**options)
    context = browser.new_context(viewport={'width':1440,'height':1100})
    context.add_init_script("""Object.defineProperty(navigator, 'clipboard', { configurable:true, value: {
      writeText: async text => { window.__copied = text; }
    }});""")
    page = context.new_page()
    errors, external = [], []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('request', lambda r: external.append(r.url) if not r.url.startswith(BASE) else None)
    page.goto(BASE)
    expect(page.locator('#workspace')).to_be_visible()
    check(page.title() == 'N2 Controlled Kaiwa Trainer','page loads with local data')
    expect(page.locator('#english-question')).to_be_visible()
    expect(page.locator('#meaning-hint')).to_be_visible()
    expect(page.locator('#japanese-question')).to_be_hidden()
    expect(page.locator('#japanese-answer')).to_be_hidden()
    page.locator('#toggle-question').click()
    expect(page.locator('#japanese-question')).to_be_visible()
    expect(page.locator('#japanese-answer')).to_be_hidden()
    page.locator('#toggle-answer').click()
    page.locator('#toggle-question').click()
    expect(page.locator('#japanese-question')).to_be_hidden()
    expect(page.locator('#japanese-answer')).to_be_visible()
    check(True,'Japanese reveals are independent')
    page.locator('#copy-one').click()
    value=prompt(page,1)
    check(bank[0]['japaneseQuestion'] in value and bank[0]['englishQuestion'] in value,'exact source-linked questions copied')
    page.locator('#next').click()
    expect(page.locator('#japanese-answer')).to_be_hidden()
    check(page.locator('#stt').inner_text()=='STT 002','navigation advances and hides answer')
    page.locator('#round').select_option('2')
    page.locator('#copy-five').click()
    value=prompt(page,5)
    check([int(n) for n in re.findall(r'Original grammar STT: (\d+)',value)]==list(range(6,11)),'Round 2 copies STT 6–10')
    page.locator('#day').select_option('22')
    check(page.locator('#round option').count()==1,'final day has one short round')
    page.locator('#copy-five').click()
    prompt(page,4)
    page.locator('#day').select_option('1')
    page.locator('#copy-ten').click()
    check(page.locator('#random-list li').count()==10,'Copy 10Qs displays preview before copying')
    check('EXERCISES (4)' in page.evaluate('window.__copied'),'preview does not overwrite clipboard')
    page.locator('#copy-random').click()
    value=prompt(page,10)
    ids=[int(n) for n in re.findall(r'Original grammar STT: (\d+)',value)]
    check(len(set(ids))==10 and max(ids)<=10,'default random pool uses covered grammar without duplicates')
    page.locator('#copy-ten').click()
    page.locator('#random-scope').select_option('all')
    page.locator('#copy-random').click()
    value=prompt(page,10)
    check(len(set(re.findall(r'Original grammar STT: (\d+)',value)))==10,'entire-bank random pool is unique')
    check(page.locator('[data-mode]').count()==2 and page.locator('[data-mode=review]').count()==0,'only Daily and Custom tabs remain')
    check(page.locator('[id^=practice-]').count()==0 and page.locator('#open-shortcut').count()==0,'copy area has no Shortcut actions')
    page.locator('#choose-grammar').click()
    check(page.locator('#grammar-options input').count()==214,'all 214 grammar entries are listed before any day is checked')
    page.locator('#grammar-options input[value="214"]').check()
    check(page.locator('#custom-days input[value="22"]').evaluate('(e)=>e.indeterminate'),'individual grammar can be selected directly with no day preselection')
    page.locator('#clear-selection').click()
    check(page.locator('#grammar-options input').count()==214,'clearing selections keeps the complete list visible')
    page.locator('#grammar-search').fill('157')
    page.locator('#grammar-options input').check()
    page.locator('#grammar-search').fill('114')
    page.locator('#grammar-options input').check()
    page.locator('#apply-selection').click()
    check(page.locator('#stt').inner_text()=='STT 114','custom grammar sorted by original STT')
    page.locator('#copy-five').click()
    value=prompt(page,2)
    check('Original grammar STT: 157' in value,'custom round contains exactly the selected entries')
    page.locator('[data-mode=custom]').click()
    page.locator('#clear-selection').click()
    check(page.locator('#apply-selection').is_disabled(),'empty Custom selection cannot start')
    page.locator('#custom-days input[value="1"]').check()
    check(page.locator('#grammar-options input:checked').count()==10,'D1 selects all 10 grammar entries below')
    page.locator('#custom-days input[value="2"]').check()
    check(page.locator('#grammar-options input:checked').count()==20,'D1 and D2 can both be selected')
    page.locator('#grammar-options input[value="3"]').uncheck()
    check(page.locator('#custom-days input[value="1"]').evaluate('(e)=>e.indeterminate'),'unticking one grammar makes D1 partially selected')
    check('9/10' in page.locator('#custom-days label').first.inner_text(),'day badge reflects individual unticks')
    page.locator('#apply-selection').click()
    check(page.locator('#round option').count()==4,'19 selected structures split into rounds of five')
    page.locator('#next').click();page.locator('#next').click()
    check(page.locator('#stt').inner_text()=='STT 004','Custom practice skips the unticked confident structure')
    page.locator('#copy-ten').click()
    check(page.locator('#random-scope').input_value()=='custom','Custom random practice defaults to checked grammar')
    page.locator('#copy-random').click();value=prompt(page,10)
    check(all(int(n)<=20 and int(n)!=3 for n in re.findall(r'Original grammar STT: (\d+)',value)),'Custom random prompt excludes unticked grammar')
    page.locator('[data-mode=custom]').click()
    page.locator('#custom-days input[value="2"]').uncheck()
    check(page.locator('#grammar-options input:checked').count()==9,'unticking D2 removes only D2 grammar')
    check(page.locator('#grammar-options input').count()==214,'unticking a day never hides its grammar list')
    page.locator('#apply-selection').click()
    page.locator('#copy-ten').click()
    check(page.locator('#copy-random').is_disabled() and page.locator('#random-list li').count()==0,'fewer than 10 Custom entries never fabricate duplicates')
    page.locator('#random-dialog [data-close]').click()
    page.locator('[data-mode=custom]').click()
    page.locator('#clear-selection').click()
    page.locator('#custom-days input[value="22"]').check()
    check(page.locator('#grammar-options input:checked').count()==4,'D22 selects exactly four source entries')
    page.locator('#custom-days input[value="1"]').check()
    page.locator('#apply-selection').click()
    page.reload();expect(page.locator('#workspace')).to_be_visible()
    page.locator('[data-mode=custom]').click()
    check('14 structures selected' in page.locator('#selected-count').inner_text(),'all 14 Custom choices persist across reload')
    page.locator('#custom-days input[value="1"]').uncheck()
    page.locator('#custom-dialog [data-close]').click()
    page.locator('[data-mode=custom]').click()
    check('14 structures selected' in page.locator('#selected-count').inner_text(),'canceling edits preserves the applied Custom selection')
    page.locator('#apply-selection').click()
    # Reject both clipboard APIs to exercise the real manual fallback.
    page.evaluate("navigator.clipboard.writeText = async () => { throw new Error('denied'); }; document.execCommand = () => false;")
    page.locator('#copy-one').click()
    expect(page.locator('#handoff-dialog')).to_be_visible()
    check('EXERCISES (1)' in page.locator('#prompt-text').input_value(),'complete prompt available for manual copy')
    page.locator('#select-prompt').click()
    check(page.locator('#prompt-text').evaluate('(e)=>e.selectionEnd-e.selectionStart===e.value.length'),'manual copy selects the complete prompt')
    page.locator('#handoff-dialog [data-close]').click()
    page.locator('[data-mode=daily]').click()
    page.locator('#day').select_option('3')
    page.reload(); expect(page.locator('#workspace')).to_be_visible()
    check(page.locator('#day').input_value()=='3','learning preference persists')
    page.locator('#day').select_option('1')
    Path('/tmp/n2-test-results').mkdir(exist_ok=True)
    page.screenshot(path='/tmp/n2-test-results/desktop.png',full_page=True)
    for width,height,label in [(390,844,'iPhone'),(768,1024,'iPad'),(320,700,'small-mobile')]:
        page.set_viewport_size({'width':width,'height':height})
        check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'),f'{label} has no horizontal overflow')
        page.locator('#next').click()
        expect(page.locator('#stt')).to_contain_text('002')
        page.locator('#previous').click()
        page.locator('#help-button').click()
        expect(page.locator('#help-dialog')).to_be_visible()
        check(page.locator('#help-dialog').evaluate('(e)=>e.getBoundingClientRect().width <= innerWidth'),f'{label} setup dialog fits')
        page.locator('#help-dialog [data-close]').click()
        page.locator('[data-mode=custom]').click()
        check(page.locator('#custom-dialog').evaluate('(e)=>e.scrollWidth<=e.clientWidth'),f'{label} Custom day selector has no horizontal overflow')
        check(page.locator('#custom-days label').first.evaluate('(e)=>e.getBoundingClientRect().height>=44'),f'{label} day selection has touch-friendly targets')
        page.screenshot(path=f'/tmp/n2-test-results/{label}-custom.png',full_page=True)
        page.locator('#custom-dialog [data-close]').click()
        page.screenshot(path=f'/tmp/n2-test-results/{label}.png',full_page=True)
    check(not errors,f'no browser errors: {errors}')
    check(not external,f'no external runtime requests: {external}')
    # Local storage unavailable: basic workflow must remain functional.
    private=context.new_page()
    private.add_init_script("Object.defineProperty(window,'localStorage',{get(){throw new Error('unavailable')}})")
    private.goto(BASE)
    expect(private.locator('#workspace')).to_be_visible()
    private.locator('#next').click()
    expect(private.locator('#stt')).to_contain_text('002')
    check(True,'app works with localStorage unavailable')
    browser.close()
print(f'{checks} browser assertions passed ({name}).')
